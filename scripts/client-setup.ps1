# One-command client setup for Windows: build (or copy) pgtun, write a JSON
# config, register a logon Scheduled Task and print the ss:// link, base64
# subscription, QR and the device command.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File .\scripts\client-setup.ps1 -Dsn "<DSN>"
#
# Params:
#   -Dsn DSN            PostgreSQL DSN (required unless the config already has one; env PGTUN_DSN)
#   -Socks ADDR         SOCKS5 listen address (default 127.0.0.1:1080)
#   -Ss ADDR            Shadowsocks listen address (default 0.0.0.0:8388)
#   -SsMethod M         Shadowsocks AEAD method (default chacha20-ietf-poly1305)
#   -SsPassword P       Shadowsocks password (auto-generated if absent)
#   -PublicHost H       host advertised in the subscription (default: detected)
#   -Tag T              subscription name (default pgtun)
#   -BinDir DIR         install dir (default %LOCALAPPDATA%\pgtun)
#   -Config FILE        JSON config path (default %APPDATA%\pgtun\client.json)
#   -PrintOnly          build + write config + print subscription, then exit
#   -DryRun             print the plan and exit without writing/installing
#   -Uninstall          remove the logon Scheduled Task (keep binary/config)
#
# Idempotent: safe to re-run.

[CmdletBinding()]
param(
    [string]$Dsn = "",
    [string]$Socks = "127.0.0.1:1080",
    [string]$Ss = "0.0.0.0:8388",
    [string]$SsMethod = "chacha20-ietf-poly1305",
    [string]$SsPassword = "",
    [string]$PublicHost = "",
    [string]$Tag = "pgtun",
    [string]$BinDir = "$env:LOCALAPPDATA\pgtun",
    [string]$Config = "$env:APPDATA\pgtun\client.json",
    [switch]$PrintOnly,
    [switch]$DryRun,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot 'go.mod')) -or
    -not (Test-Path -LiteralPath (Join-Path $RepoRoot 'cmd\pgtun'))) {
    throw "Cannot find the pgtun repo root at $RepoRoot. Run scripts\client-setup.ps1 from the repo."
}

$Exe = Join-Path $BinDir 'pgtun.exe'
$TaskName = 'pgtun-client'

# --- uninstall -------------------------------------------------------------

if ($Uninstall) {
    & schtasks.exe /Delete /F /TN $TaskName 2>$null | Out-Null
    Write-Host "Removed Scheduled Task $TaskName (binary and config kept)."
    exit 0
}

# --- existing config values ------------------------------------------------

$ExistingDsn = ''
$ExistingPassword = ''
if (Test-Path -LiteralPath $Config) {
    try {
        $existing = Get-Content -Raw -LiteralPath $Config | ConvertFrom-Json
        if ($existing.dsn) { $ExistingDsn = [string]$existing.dsn }
        if ($existing.ss_password) { $ExistingPassword = [string]$existing.ss_password }
    } catch {
        Write-Warning "Could not parse existing config $Config; ignoring it."
    }
}

if ([string]::IsNullOrEmpty($Dsn)) {
    if (-not [string]::IsNullOrEmpty($ExistingDsn)) {
        $Dsn = $ExistingDsn
    } elseif (-not [string]::IsNullOrEmpty($env:PGTUN_DSN)) {
        $Dsn = $env:PGTUN_DSN
    }
}
if ([string]::IsNullOrEmpty($SsPassword)) {
    $SsPassword = $ExistingPassword
}

$NeedGen = [string]::IsNullOrEmpty($SsPassword)

if ([string]::IsNullOrEmpty($Dsn)) {
    throw '-Dsn (or env PGTUN_DSN) is required, unless the config already contains "dsn".'
}

# --- dry run ---------------------------------------------------------------

if ($DryRun) {
    $go = Get-Command go -ErrorAction SilentlyContinue
    if ($go) { $goLine = $go.Source } else { $goLine = 'NOT FOUND (install Go before running without -DryRun)' }
    if ($NeedGen) { $passLine = '<auto-generated 32 hex chars>' } else { $passLine = '<set>' }

    Write-Host 'pgtun client setup plan (-DryRun, nothing written or installed)'
    Write-Host ''
    Write-Host "  repo root:   $RepoRoot"
    Write-Host "  go:          $goLine"
    Write-Host "  binary:      $Exe"
    Write-Host "  build:       go build -o `"$Exe`" ./cmd/pgtun"
    Write-Host "  config:      $Config"
    Write-Host "  task:        schtasks /Create /F /SC ONLOGON /TN $TaskName /TR `"`"$Exe`" client --config `"$Config`"`""
    Write-Host "  status:      schtasks /Query /TN $TaskName"
    Write-Host "  dsn:         $Dsn"
    Write-Host "  socks:       $Socks"
    Write-Host "  ss:          $Ss"
    Write-Host "  ss_method:   $SsMethod"
    Write-Host "  ss_password: $passLine"
    Write-Host '  max_streams: 256'
    Write-Host "  tag:         $Tag"
    if ([string]::IsNullOrEmpty($PublicHost)) {
        Write-Host '  public_host: <auto-detected>'
    } else {
        Write-Host "  public_host: $PublicHost"
    }
    Write-Host ''
    exit 0
}

# --- password --------------------------------------------------------------

if ($NeedGen) {
    try {
        $bytes = New-Object byte[] 16
        $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
        $rng.GetBytes($bytes)
        $rng.Dispose()
        $SsPassword = -join ($bytes | ForEach-Object { $_.ToString('x2') })
    } catch {
        $SsPassword = ([guid]::NewGuid().ToString('N'))
    }
}

# --- binary ----------------------------------------------------------------

$go = Get-Command go -ErrorAction SilentlyContinue
if ($go) {
    Write-Host "Building pgtun -> $Exe"
    New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
    Push-Location $RepoRoot
    try {
        & go build -o $Exe ./cmd/pgtun
        if ($LASTEXITCODE -ne 0) { throw "go build failed (exit $LASTEXITCODE)." }
    } finally {
        Pop-Location
    }
} else {
    $distExe = Join-Path $RepoRoot 'dist\pgtun-windows-amd64.exe'
    if (-not (Test-Path -LiteralPath $distExe)) {
        throw ('Go toolchain not found and ' + $distExe + ' is missing. ' +
               'Install Go from https://go.dev/dl/, or run "make release" on another machine ' +
               'and copy dist\pgtun-windows-amd64.exe here.')
    }
    Write-Host "Go not found; copying $distExe -> $Exe"
    New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
    Copy-Item -LiteralPath $distExe -Destination $Exe -Force
}

# --- config ----------------------------------------------------------------

Write-Host "Writing config -> $Config"
$configDir = Split-Path -Parent $Config
if ($configDir) {
    New-Item -ItemType Directory -Force -Path $configDir | Out-Null
}

$cfg = [ordered]@{
    dsn         = $Dsn
    socks       = $Socks
    ss          = $Ss
    ss_method   = $SsMethod
    ss_password = $SsPassword
    max_streams = 256
    public_host = $PublicHost
    tag         = $Tag
}
$json = $cfg | ConvertTo-Json
$utf8NoBom = New-Object -TypeName System.Text.UTF8Encoding -ArgumentList $false
[System.IO.File]::WriteAllText($Config, $json, $utf8NoBom)

try {
    $user = "$env:USERDOMAIN\$env:USERNAME"
    & icacls.exe $Config /inheritance:r /grant:r ('{0}:(F)' -f $user) | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'icacls failed' }
} catch {
    Write-Warning "Could not restrict the ACL on $Config; restrict it manually if needed."
}

function Show-DeviceBlocks {
    Write-Host ''
    Write-Host '=== КОМАНДА ДЛЯ ЭТОГО УСТРОЙСТВА (SOCKS5) ==='
    Write-Host ("{0} client --config {1}" -f $Exe, $Config)
    Write-Host '=== ПОДПИСКА ДЛЯ HAPP/ТЕЛЕФОНА ==='
    Write-Host '(ss:// выше — отсканируй QR или вставь base64-подписку)'
}

# --- print-only ------------------------------------------------------------

if ($PrintOnly) {
    & $Exe client --config $Config --print-sub
    if ($LASTEXITCODE -ne 0) { throw 'pgtun --print-sub failed.' }
    Show-DeviceBlocks
    exit 0
}

# --- install logon task ----------------------------------------------------

Write-Host "Registering logon Scheduled Task $TaskName"
$registered = $false
if (Get-Command Register-ScheduledTask -ErrorAction SilentlyContinue) {
    try {
        $action = New-ScheduledTaskAction -Execute $Exe -Argument ('client --config "{0}"' -f $Config)
        $trigger = New-ScheduledTaskTrigger -AtLogOn
        Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Force | Out-Null
        $registered = $true
    } catch {
        Write-Warning "Register-ScheduledTask failed: $($_.Exception.Message). Falling back to schtasks."
    }
}
if (-not $registered) {
    $tr = '"{0}" client --config "{1}"' -f $Exe, $Config
    & schtasks.exe /Create /F /SC ONLOGON /TN $TaskName /TR $tr | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'schtasks /Create failed.' }
}

# --- subscription, status, hints ------------------------------------------

& $Exe client --config $Config --print-sub
if ($LASTEXITCODE -ne 0) { throw 'pgtun --print-sub failed.' }
Show-DeviceBlocks

Write-Host ''
Write-Host 'Status:'
& schtasks.exe /Query /TN $TaskName
Write-Host ''
Write-Host ("Check:     schtasks /Query /TN {0}" -f $TaskName)
Write-Host 'Uninstall: powershell -ExecutionPolicy Bypass -File .\scripts\client-setup.ps1 -Uninstall'
